#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT/backend"
mkdir -p seed_docs

if [ ! -f "seed_docs/员工手册.md" ]; then
cat > "seed_docs/员工手册.md" <<'MD'
# 员工手册

## 年假
员工每年享有 10 天带薪年假，入职满一年后即可申请，可在钉钉 OA 提交年假申请。年假当年有效，最多结转 3 天到下一年。

## 请假
事假需提前 3 个工作日申请；病假需在请假当天提交，连续病假超过 3 天需提供医院证明。婚假 10 天，产假按国家和地方规定执行，陪产假 15 天。

## 报销
报销发票需要提供：发票原件、报销单、审批通过截图，缺一不可。报销流程 3 个工作日内完成审核，每月 25 日截止当月报销单提交。

## 考勤
工作时间 9:00-18:00，午休 1 小时。迟到超过 30 分钟记一次迟到，当月迟到 3 次将计入绩效沟通。加班需提前审批，工作日加班按 1.5 倍时薪计算，周末 2 倍，法定节假日 3 倍。

## 出差
出差需提前提交出差申请单，住宿标准：一线城市 500 元/晚，其他城市 350 元/晚。出差交通费凭票实报实销，市内交通每天上限 100 元。

## 社保与公积金
公司按国家和当地规定为员工缴纳五险一金，公积金个人与公司各缴存 12%。具体基数每年 7 月调整一次。

## 信息安全
员工账号不得共享，密码至少 12 位并开启双因素认证。涉及客户数据、订单数据和内部系统的内容不得外发，发现疑似泄露须立即报告 IT 部门。
MD
echo "生成 seed_docs/员工手册.md"
fi

if [ ! -f "seed_docs/FAQ.md" ]; then
cat > "seed_docs/FAQ.md" <<'MD'
# 员工 FAQ

Q: 加班有加班费吗？
A: 有，工作日加班 1.5 倍时薪，周末 2 倍，法定节假日 3 倍。

Q: 年假可以结转吗？
A: 年假当年有效，最多结转 3 天到下一年。

Q: 忘记打卡怎么办？
A: 在钉钉 OA 提交补卡申请，每月最多 3 次，需直属上级审批。

Q: 可以远程办公吗？
A: 每周五可申请远程办公，需提前一天审批。

Q: 请事假需要提前多久申请？
A: 事假需提前 3 个工作日申请，并在钉钉 OA 提交请假单。

Q: 病假需要证明吗？
A: 连续病假超过 3 天需提供医院证明；1-3 天病假在 OA 提交即可。

Q: 公积金缴存比例是多少？
A: 个人与公司各缴存 12%，具体基数按当地规定执行。

Q: 报销多久到账？
A: 报销审核 3 个工作日内完成，财务付款一般在审核通过后的 5 个工作日内。

Q: 出差住宿标准是多少？
A: 一线城市 500 元/晚，其他城市 350 元/晚。

Q: 市内交通怎么报销？
A: 凭发票实报实销，每天上限 100 元。

Q: 新员工试用期多久？
A: 试用期 3 个月，转正需通过 360 评估。

Q: 电脑坏了找谁？
A: 联系 IT 支持，工作时间内响应不超过 2 小时。

Q: 企业邮箱怎么申请？
A: 入职当天 HR 会开通企业邮箱和钉钉账号，无需自行申请。

Q: 可以申请调休吗？
A: 周末加班可优先申请调休，调休需在 3 个月内使用。

Q: 年假可以提前休吗？
A: 入职满一年后可申请；特殊情况经部门负责人审批可提前安排。

Q: 设备申领流程是什么？
A: 入职第一天到 HR 领取工牌，电脑由 IT 提前配置，联系 IT 领取即可。

Q: 客户数据能带回家处理吗？
A: 不可以。客户数据、订单数据必须在公司内部系统或经批准的加密环境中处理。

Q: 遇到钓鱼邮件怎么办？
A: 不要点击链接或附件，立即转发给 security@example.com 并通知 IT。

Q: 出差申请在哪提交？
A: 在钉钉 OA 的「出差申请」流程提交，审批通过后方可出行。

Q: 报销发票丢失怎么办？
A: 联系财务确认是否可用电子发票替代；普通发票不支持补报。
MD
echo "生成 seed_docs/FAQ.md"
fi

if [ ! -f "seed_docs/新人入职指南.md" ]; then
cat > "seed_docs/新人入职指南.md" <<'MD'
# 新人入职指南

## 入职第一天
新人入职第一天要做的事：
1. 到 HR 处领取工牌与电脑（IT 会提前配好）
2. 开通企业邮箱与钉钉账号
3. 参加 10:00 的新人培训
4. 与直属上级确认第一周计划
5. 在 OA 完成劳动合同与个人信息确认

## 试用期
试用期 3 个月，转正需通过 360 评估。试用期期间直属上级每周进行一次 1v1，第三个月进行转正答辩。

## 常用系统
- 考勤打卡：钉钉 OA
- 请假/报销/出差：钉钉 OA 审批
- 文档与知识库：内部 Wiki
- 客户与订单：订单管理系统

## 导师制度
入职前两周由导师带教，导师负责账号权限、代码/业务说明和第一个任务的拆解。
MD
echo "生成 seed_docs/新人入职指南.md"
fi

if [ ! -f "seed_docs/信息安全与账号制度.md" ]; then
cat > "seed_docs/信息安全与账号制度.md" <<'MD'
# 信息安全与账号制度

## 账号与密码
员工账号不得共享。密码至少 12 位，包含大小写字母、数字和符号，并开启双因素认证。每 90 天更换一次密码。

## 数据分级
公司数据分为公开、内部、机密三级。客户数据、员工薪资、订单明细属于机密数据，仅限授权人员访问。

## 设备要求
办公电脑必须安装公司要求的杀毒与终端管理软件。个人设备访问内部系统需通过 VPN，并在访问结束后及时退出。

## 事件上报
发现可疑邮件、异常登录或数据泄露风险，须在 30 分钟内通知 IT 安全团队，并保留现场证据，不得自行删除日志。

## 外部沟通
对外发布产品信息、销售数据、合作细节需经市场与法务审核。未经授权不得向外部提供内部文档。
MD
